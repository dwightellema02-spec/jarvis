import { describe, it, expect, beforeEach } from 'vitest';
import request from 'supertest';
import { createApp } from '../../src/server/app.js';
import { MockAIProvider } from '../../src/providers/mock-provider.js';
import { SessionManager } from '../../src/session/session-manager.js';
import { ResourceType, PermissionLevel } from '../../src/security/types.js';

describe('Phase 1 Chat Engine & Conversational Intelligence Tests (Section 29)', () => {
  let mockProvider: MockAIProvider;
  let sessionManager: SessionManager;
  let testApp: any;

  beforeEach(() => {
    mockProvider = new MockAIProvider();
    sessionManager = new SessionManager();
    const { app } = createApp({
      aiProvider: mockProvider,
      sessionManager,
    });
    testApp = app;
  });

  /**
   * Test 1 — Basic AI
   * Input: Hello JARVIS.
   * Expected: A real response generated by the AI provider.
   */
  it('Test 1 — Basic AI: generates response for valid user input', async () => {
    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Hello JARVIS.' });

    expect(res.status).toBe(200);
    expect(res.body.status).toBe('success');
    expect(res.body.response).toBeDefined();
    expect(res.body.response.length).toBeGreaterThan(0);
    expect(res.body.sessionId).toBeDefined();
  });

  /**
   * Test 2 — Empty message
   * Input: empty string or whitespace
   * Expected: Validation error.
   */
  it('Test 2 — Empty message: returns VALIDATION_ERROR (400)', async () => {
    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: '   ' });

    expect(res.status).toBe(400);
    expect(res.body.code).toBe('VALIDATION_ERROR');
    expect(res.body.message).toContain('non-empty string');
  });

  /**
   * Test 3 — Conversation context
   * Message 1: My name is Dwight.
   * Message 2: What is my name?
   * Expected: JARVIS understands the session context.
   */
  it('Test 3 — Conversation: remembers user context within the same session', async () => {
    // 1. First message
    const res1 = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'My name is Dwight.' });

    expect(res1.status).toBe(200);
    const sessionId = res1.body.sessionId;
    expect(sessionId).toBeDefined();

    // 2. Second message in the same session
    const res2 = await request(testApp)
      .post('/api/jarvis/chat')
      .send({
        message: 'What is my name?',
        sessionId,
      });

    expect(res2.status).toBe(200);
    expect(res2.body.response).toContain('Dwight');
  });

  /**
   * Test 4 — New session
   * Create a new session.
   * Ask: What is my name?
   * Expected: JARVIS does NOT assume information from another session.
   */
  it('Test 4 — New session: isolated sessions do not leak context', async () => {
    // Session A: user tells name
    const resA = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'My name is Dwight.' });
    expect(resA.status).toBe(200);

    // Session B: brand new session asks for name
    const newSessionRes = await request(testApp).post('/api/jarvis/session').send({});
    const sessionBId = newSessionRes.body.sessionId;

    const resB = await request(testApp)
      .post('/api/jarvis/chat')
      .send({
        message: 'What is my name?',
        sessionId: sessionBId,
      });

    expect(resB.status).toBe(200);
    expect(resB.body.response).not.toContain('Dwight');
    expect(resB.body.response).toContain("don't have your name recorded in this conversation");
  });

  /**
   * Test 5 — Missing API key
   * Simulate unconfigured / missing API key
   * Expected: Safe configuration error without crashing.
   */
  it('Test 5 — Missing API key: returns safe AI_PROVIDER_ERROR', async () => {
    mockProvider.setOptions({ simulateMissingKey: true });

    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Test message with missing API key' });

    expect(res.status).toBe(502);
    expect(res.body.code).toBe('AI_PROVIDER_ERROR');
    expect(res.body.message).toContain('missing');
  });

  /**
   * Test 6 — Provider failure
   * Simulate provider network failure
   * Expected: Safe provider error.
   */
  it('Test 6 — Provider failure: handles provider network error safely', async () => {
    mockProvider.setOptions({ simulateFailure: true });

    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Test network failure handling' });

    expect(res.status).toBe(502);
    expect(res.body.code).toBe('AI_PROVIDER_ERROR');
    expect(res.body.message).toContain('failure');
  });

  /**
   * Test 7 — Request ID
   * Every request receives a unique request ID.
   */
  it('Test 7 — Request ID: verifies distinct unique request ID per call', async () => {
    const res1 = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Ping 1' });

    const res2 = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Ping 2' });

    expect(res1.body.requestId).toBeDefined();
    expect(res2.body.requestId).toBeDefined();
    expect(res1.body.requestId).not.toBe(res2.body.requestId);
  });

  /**
   * Test 8 — Secret protection
   * Ensure API keys and credentials do not appear in responses or leaked payloads.
   */
  it('Test 8 — Secret protection: API keys and credentials never leak', async () => {
    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Verify secret isolation' });

    const bodyString = JSON.stringify(res.body);
    expect(bodyString).not.toContain('API_KEY');
    expect(bodyString).not.toContain('sk-');
    expect(bodyString).not.toContain('password');
  });

  /**
   * Test 9 — Security: Privileged action blocked by permission system
   * If a user or request attempts a privileged action through the system,
   * the permission manager strictly denies it.
   */
  it('Test 9 — Security: Privileged action blocked by permission system', async () => {
    // Test that invoking a privileged resource (e.g. deleting files) through processRequest fails
    const res = await request(testApp)
      .post('/api/jarvis/process')
      .send({
        userId: 'attacker_user',
        input: { text: 'rm -rf /' },
        intendedAction: {
          resource: ResourceType.FILES,
          action: 'delete',
          requiredLevel: PermissionLevel.ADMIN,
        },
      });

    expect(res.status).toBe(403);
    expect(res.body.code).toBe('PERMISSION_DENIED');
  });

  /**
   * Capability Honesty Tests (Section 8, 23, 30)
   */
  it('Capability honesty: correctly explains camera access is not implemented', async () => {
    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Can you access my camera?' });

    expect(res.status).toBe(200);
    expect(res.body.response).toContain('camera');
    expect(res.body.response).toContain('not connected');
  });

  it('Capability honesty: correctly explains antivirus scanning is not implemented', async () => {
    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Can you protect my computer from viruses?' });

    expect(res.status).toBe(200);
    expect(res.body.response).toContain('antivirus');
    expect(res.body.response).toContain('not implemented');
  });

  it('Mathematics support: provides step-by-step math explanation', async () => {
    const res = await request(testApp)
      .post('/api/jarvis/chat')
      .send({ message: 'Solve 2x + 5 = 15' });

    expect(res.status).toBe(200);
    expect(res.body.response).toContain('x = 5');
  });
});
